# ---------------------------------------------------------------------------
# Internal prediction engine (MultiSpline 0.3.0)
#
# Every quantity that is a function of the fitted curve (predictions, their
# standard errors, derivatives, marginal curves) is computed from the
# fixed-effects design matrix evaluated at new x values. That design matrix
# must be built with the *training* spline basis (same knots). The terms
# object of a fitted model carries this information in its "predvars"
# attribute, so we always build new design matrices through it.
# ---------------------------------------------------------------------------

# Fixed-effects terms (with predvars) for any supported model class.
.fixed_terms <- function(mod) {
  tt <- if (inherits(mod, "merMod")) {
    stats::terms(mod, fixed.only = TRUE)
  } else {
    stats::terms(mod)
  }
  stats::delete.response(tt)
}

# Fixed-effects design matrix at `newdata`, built with the training basis.
.fixed_design <- function(object, newdata) {
  mod <- object$model
  if (inherits(mod, "gam")) {
    return(mgcv::predict.gam(mod, newdata = newdata, type = "lpmatrix"))
  }
  tt   <- .fixed_terms(mod)
  xlev <- if (inherits(mod, "merMod")) .merMod_xlevels(mod) else mod$xlevels
  mf   <- stats::model.frame(tt, newdata, na.action = stats::na.pass,
                             xlev = xlev)
  X    <- stats::model.matrix(tt, mf,
                              contrasts.arg = attr(.train_X(mod), "contrasts"))
  beta <- .coef_fixed(mod)
  miss <- setdiff(names(beta), colnames(X))
  if (length(miss))
    stop("Internal error: design columns missing for new data: ",
         paste(miss, collapse = ", "), call. = FALSE)
  X[, names(beta), drop = FALSE]
}

.train_X <- function(mod) {
  if (inherits(mod, "merMod")) lme4::getME(mod, "X") else stats::model.matrix(mod)
}

.merMod_xlevels <- function(mod) {
  mf <- stats::model.frame(mod)
  grp <- names(lme4::getME(mod, "flist"))      # grouping factors only
  fx_terms <- attr(stats::terms(mod, fixed.only = TRUE), "term.labels")
  keep <- setdiff(names(mf), setdiff(grp, fx_terms))
  mf <- mf[keep]
  fx <- vapply(mf, function(v) is.factor(v) || is.character(v), logical(1))
  lv <- lapply(mf[fx], function(v) if (is.factor(v)) levels(v) else sort(unique(v)))
  if (length(lv)) lv else NULL
}

.coef_fixed <- function(mod) {
  b <- if (inherits(mod, "merMod")) lme4::fixef(mod) else stats::coef(mod)
  b[!is.na(b)]
}

.vcov_fixed <- function(mod) {
  V <- as.matrix(stats::vcov(mod))
  b <- .coef_fixed(mod)
  V[names(b), names(b), drop = FALSE]
}

.model_family <- function(object) {
  mod <- object$model
  fam <- tryCatch(stats::family(mod), error = function(e) NULL)
  if (is.null(fam)) fam <- stats::gaussian()
  fam
}

# Linear predictor, its gradient (the design matrix) and covariance.
.lp <- function(object, newdata) {
  X <- .fixed_design(object, newdata)
  b <- .coef_fixed(object$model)
  list(X = X, beta = b, V = .vcov_fixed(object$model),
       eta = drop(X %*% b), family = .model_family(object))
}

# Quadratic form diag(G V G') without forming the full matrix.
.qform <- function(G, V) sqrt(pmax(rowSums((G %*% V) * G), 0))

# ---------------------------------------------------------------------------
# Random-effect variance of the linear predictor at each row of newdata.
# Supported: random intercepts for any number of grouping factors, and the
# random spline slopes generated by nl_fit(random_slope = TRUE), whose
# random-effects design is [1, B(x)] with the same basis as the fixed part.
# Returns NULL when the random structure cannot be evaluated safely.
# ---------------------------------------------------------------------------
.re_var_newdata <- function(object, newdata) {
  mod <- object$model
  if (!inherits(mod, "merMod")) return(rep(0, nrow(newdata)))
  vc   <- lme4::VarCorr(mod)
  cnms <- lme4::getME(mod, "cnms")
  out  <- rep(0, nrow(newdata))
  Xf   <- NULL
  for (j in seq_along(vc)) {
    S  <- as.matrix(vc[[j]])
    cn <- cnms[[j]]
    if (identical(cn, "(Intercept)")) {
      out <- out + S[1L, 1L]
      next
    }
    if (isTRUE(object$random_slope)) {
      if (is.null(Xf)) Xf <- .fixed_design(object, newdata)
      if (!all(cn %in% colnames(Xf))) return(NULL)
      Z   <- Xf[, cn, drop = FALSE]
      out <- out + rowSums((Z %*% S) * Z)
      next
    }
    return(NULL)
  }
  out
}

# Gauss-Hermite nodes/weights for E[g(eta + u)], u ~ N(0, v).
.gh <- function(n = 40L) {
  i  <- seq_len(n - 1L)
  b  <- sqrt(i / 2)
  J  <- matrix(0, n, n)
  J[cbind(i, i + 1L)] <- b
  J[cbind(i + 1L, i)] <- b
  e  <- eigen(J, symmetric = TRUE)
  list(x = e$values, w = e$vectors[1L, ]^2)  # sums to 1 after /sqrt(pi)*sqrt(pi)
}

# Population-averaged mean and its gradient with respect to beta.
.marginal_mean <- function(eta, v, X, family, gh = .gh()) {
  if (identical(family$link, "identity"))
    return(list(mu = eta, G = X))
  nodes <- sqrt(2) * gh$x
  mu <- numeric(length(eta)); dmu <- numeric(length(eta))
  for (k in seq_along(nodes)) {
    e_k <- eta + nodes[k] * sqrt(v)
    mu  <- mu  + gh$w[k] * family$linkinv(e_k)
    dmu <- dmu + gh$w[k] * family$mu.eta(e_k)
  }
  list(mu = mu, G = X * dmu)
}

# Mean on the requested scale plus gradient wrt beta, for a newdata frame.
#   type  = "conditional": random effects set to zero
#   type  = "marginal"   : averaged over the random-effect distribution
#   scale = "response" or "link"
.mean_and_grad <- function(object, newdata, type = "conditional",
                           scale = "response") {
  lp  <- .lp(object, newdata)
  fam <- lp$family
  if (scale == "link" || identical(fam$link, "identity"))
    return(list(mu = lp$eta, G = lp$X, V = lp$V))
  if (type == "marginal") {
    v <- .re_var_newdata(object, newdata)
    if (is.null(v))
      stop("Marginal predictions are not available for this random-effects ",
           "structure.", call. = FALSE)
    m <- .marginal_mean(lp$eta, v, lp$X, fam)
    return(list(mu = m$mu, G = m$G, V = lp$V))
  }
  list(mu = fam$linkinv(lp$eta), G = lp$X * fam$mu.eta(lp$eta), V = lp$V)
}

# ---------------------------------------------------------------------------
# Variance components of the linear predictor, averaged over the estimation
# sample (Johnson 2014): for each random-effects term with design Z and
# covariance S, mean_i z_i' S z_i. Equals sigma^2 for a random intercept.
# ---------------------------------------------------------------------------
.re_components <- function(mod) {
  vc   <- lme4::VarCorr(mod)
  cnms <- lme4::getME(mod, "cnms")
  mms  <- NULL
  out  <- vapply(seq_along(vc), function(j) {
    S <- as.matrix(vc[[j]])
    if (identical(cnms[[j]], "(Intercept)")) return(S[1L, 1L])
    if (is.null(mms)) mms <<- suppressWarnings(lme4::getME(mod, "mmList"))
    Z <- as.matrix(mms[[j]])
    mean(rowSums((Z %*% S) * Z))
  }, numeric(1))
  nm <- names(cnms)
  dup <- duplicated(nm) | duplicated(nm, fromLast = TRUE)
  if (any(dup)) {
    lab <- vapply(cnms, paste, character(1), collapse = "+")
    nm[dup] <- paste0(nm[dup], " [", lab[dup], "]")
  }
  attr(out, "slopes") <- vapply(cnms, function(z) !identical(z, "(Intercept)"),
                                logical(1))
  stats::setNames(out, nm)
}

# Distribution-specific (latent-scale) variance for GLMMs (Nakagawa et al.
# 2017). Gaussian models return the residual variance.
.dist_var <- function(mod) {
  if (inherits(mod, "lmerMod")) return(stats::sigma(mod)^2)
  fam <- stats::family(mod)
  if (fam$family == "binomial") {
    return(switch(fam$link, logit = pi^2 / 3, probit = 1,
                  cloglog = pi^2 / 6, NA_real_))
  }
  if (fam$family == "poisson" && fam$link == "log") {
    re  <- sum(.re_components(mod))
    lam <- exp(lme4::fixef(mod)[1L] + re / 2)
    return(unname(log(1 + 1 / lam)))
  }
  NA_real_
}

.fixed_var <- function(mod) {
  stats::var(as.numeric(lme4::getME(mod, "X") %*% lme4::fixef(mod)))
}


# Likelihood-ratio test between two nested mixed models on their ML fits.
# Computed from the log-likelihoods directly, so it does not depend on
# anova.merMod() re-evaluating the data argument of the model calls.
.ml_lrt <- function(m0, m1) {
  ml <- function(m) if (inherits(m, "lmerMod") && lme4::isREML(m))
    lme4::refitML(m) else m
  l0 <- stats::logLik(ml(m0)); l1 <- stats::logLik(ml(m1))
  k0 <- attr(l0, "df"); k1 <- attr(l1, "df")
  chi <- max(0, 2 * (as.numeric(l1) - as.numeric(l0)))
  data.frame(model = c("random intercept", "random slopes"),
             npar = c(k0, k1),
             AIC = c(-2 * as.numeric(l0) + 2 * k0, -2 * as.numeric(l1) + 2 * k1),
             logLik = c(as.numeric(l0), as.numeric(l1)),
             Chisq = c(NA, chi), Df = c(NA, k1 - k0),
             p.value = c(NA, stats::pchisq(chi, k1 - k0, lower.tail = FALSE)))
}

# findbars() moved from lme4 to reformulas (lme4 >= 2.0 warns on the old one).
.findbars <- function(f) {
  if (requireNamespace("reformulas", quietly = TRUE)) reformulas::findbars(f)
  else lme4::findbars(f)
}
